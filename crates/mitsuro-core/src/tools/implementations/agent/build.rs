fn deduplicate_background_processes(processes: &mut Vec<DelegatedProcessArtifact>) {
    processes.sort_by(|left, right| left.process_id.cmp(&right.process_id));
    processes.dedup_by(|left, right| left.process_id == right.process_id);
}

async fn revalidate_background_processes(
    processes: &mut [DelegatedProcessArtifact],
    registry: Option<&crate::process::ProcessRegistry>,
    legacy_process_owner_id: Option<&str>,
) {
    let Some(registry) = registry else {
        // A captured startup result is not sufficient proof at finalization if
        // the inherited registry is unavailable. Keep the artifact for audit,
        // but make sure it cannot be classified as an active handoff.
        for process in processes {
            process.status = "unverified".to_string();
        }
        return;
    };

    for process in processes {
        let owner_id = if process.owner_id.is_empty() {
            legacy_process_owner_id
        } else {
            Some(process.owner_id.as_str())
        };
        let current = match owner_id {
            Some(owner_id) => registry.get_for_user(owner_id, &process.process_id).await,
            // Single-tenant callers use the registry's default owner. Process
            // IDs are generated by the registry and originate in this result.
            None => registry.get(&process.process_id).await,
        };
        process.status = current
            .as_ref()
            .map(|info| info.display_status().to_string())
            .unwrap_or_else(|| "missing".to_string());
    }
}

async fn discard_unowned_build_isolation(
    isolation: &mut Vec<BuildIsolationSet>,
    delegated_run_id: &str,
) {
    for isolation in std::mem::take(isolation) {
        let isolation_group_id = isolation.group_id().to_string();
        if let Err(error) = isolation.discard().await {
            warn!(
                delegated_run_id,
                isolation_group_id,
                %error,
                "Failed to discard an unowned delegated build isolation batch"
            );
        }
    }
}

fn active_process_handoff_summary(processes: &[DelegatedProcessArtifact]) -> Option<String> {
    let active = processes
        .iter()
        .filter(|process| {
            matches!(process.status.as_str(), "running" | "suspended")
                && !process.endpoint_hints.is_empty()
        })
        .collect::<Vec<_>>();
    if active.is_empty() {
        return None;
    }

    Some(
        active
            .iter()
            .map(|process| {
                let endpoints = if process.endpoint_hints.is_empty() {
                    String::new()
                } else {
                    format!(" at {}", process.endpoint_hints.join(", "))
                };
                format!("{} ({}){}", process.process_id, process.status, endpoints)
            })
            .collect::<Vec<_>>()
            .join("; "),
    )
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct BuildResultCounts {
    complete: usize,
    degraded: usize,
    cancelled: usize,
    usable: usize,
    failed: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AggregateEvidenceKind {
    Build,
    Report,
}

fn aggregate_evidence_kind(params: &Params) -> AggregateEvidenceKind {
    let requests_write = params.tasks.as_ref().map_or_else(
        || {
            params
                .capabilities
                .iter()
                .any(|capability| capability == "write")
        },
        |tasks| {
            tasks.iter().any(|task| {
                task.capabilities
                    .iter()
                    .any(|capability| capability == "write")
                    || !task.write_intent.is_empty()
            })
        },
    );
    if requests_write {
        AggregateEvidenceKind::Build
    } else {
        AggregateEvidenceKind::Report
    }
}

fn aggregate_outcome(
    evidence_kind: AggregateEvidenceKind,
    results_len: usize,
    counts: BuildResultCounts,
    files_modified: usize,
    has_active_process_handoff: bool,
) -> &'static str {
    if counts.cancelled > 0 {
        return "cancelled";
    }
    let incomplete = counts
        .degraded
        .saturating_add(counts.cancelled)
        .saturating_add(counts.failed);
    match evidence_kind {
        AggregateEvidenceKind::Build => classify_build_outcome_with_handoff(
            results_len,
            incomplete,
            files_modified,
            has_active_process_handoff,
        ),
        AggregateEvidenceKind::Report if counts.complete == results_len && results_len > 0 => {
            "success"
        }
        AggregateEvidenceKind::Report if counts.usable > 0 => "partial",
        AggregateEvidenceKind::Report => "failed",
    }
}

fn aggregate_outcome_reason(
    evidence_kind: AggregateEvidenceKind,
    counts: BuildResultCounts,
    files_modified: usize,
    has_active_process_handoff: bool,
) -> &'static str {
    let incomplete = counts
        .degraded
        .saturating_add(counts.cancelled)
        .saturating_add(counts.failed);
    if counts.cancelled > 0 {
        return "cancelled";
    }
    match evidence_kind {
        AggregateEvidenceKind::Report if counts.complete > 0 && incomplete == 0 => {
            "report_evidence"
        }
        AggregateEvidenceKind::Report if counts.usable > 0 => "mixed_report_evidence",
        AggregateEvidenceKind::Report => "no_usable_evidence",
        AggregateEvidenceKind::Build if files_modified > 0 && incomplete == 0 => {
            "file_modifications"
        }
        AggregateEvidenceKind::Build if files_modified > 0 => "mixed",
        AggregateEvidenceKind::Build if has_active_process_handoff && incomplete == 0 => {
            "active_process_handoff_readiness_unverified"
        }
        AggregateEvidenceKind::Build if has_active_process_handoff => "partial_process_handoff",
        AggregateEvidenceKind::Build => "no_usable_evidence",
    }
}

fn aggregate_confidence(
    evidence_kind: AggregateEvidenceKind,
    counts: BuildResultCounts,
    files_modified: usize,
    has_active_process_handoff: bool,
) -> &'static str {
    let incomplete = counts
        .degraded
        .saturating_add(counts.cancelled)
        .saturating_add(counts.failed);
    match evidence_kind {
        AggregateEvidenceKind::Build => {
            build_confidence_with_handoff(incomplete, files_modified, has_active_process_handoff)
        }
        AggregateEvidenceKind::Report if counts.complete > 0 && incomplete == 0 => "high",
        AggregateEvidenceKind::Report if counts.usable > 0 => "medium",
        AggregateEvidenceKind::Report => "low",
    }
}

fn aggregate_summary(
    evidence_kind: AggregateEvidenceKind,
    counts: BuildResultCounts,
    files_modified: usize,
    lines_added: usize,
    lines_removed: usize,
    process_handoff: Option<&str>,
) -> String {
    match evidence_kind {
        AggregateEvidenceKind::Build => build_summary_with_handoff(
            counts.complete,
            counts.degraded,
            counts.cancelled,
            counts.failed,
            files_modified,
            lines_added,
            lines_removed,
            process_handoff,
        ),
        AggregateEvidenceKind::Report => format!(
            "Delegated investigation settled with {} complete, {} degraded, {} cancelled, and {} failed reports. Read-only report evidence does not require file modifications.",
            counts.complete, counts.degraded, counts.cancelled, counts.failed
        ),
    }
}

fn structured_task_working_dir(
    project_dir: &Path,
    requested_working_dir: Option<&str>,
) -> Result<PathBuf, String> {
    let project = std::fs::canonicalize(project_dir).map_err(|error| {
        format!(
            "Could not resolve Agent task workspace '{}': {error}",
            project_dir.display()
        )
    })?;
    let Some(requested) = requested_working_dir
        .map(str::trim)
        .filter(|working_dir| !working_dir.is_empty())
    else {
        return Ok(project);
    };

    let context = crate::tools::ToolContext {
        working_dir: project.clone(),
        ..Default::default()
    }
    .with_sandbox(project);
    let resolved = context
        .sandboxed_resolve(requested)
        .map_err(|error| format!("Invalid Agent task working_dir '{requested}': {error}"))?;
    if !resolved.is_dir() {
        return Err(format!(
            "Invalid Agent task working_dir '{}': expected an existing directory",
            resolved.display()
        ));
    }
    Ok(resolved)
}

fn rewrite_isolated_prompt_paths(
    prompt: &str,
    source_project: &Path,
    source_working: &Path,
    isolated_project: &Path,
    isolated_working: &Path,
) -> String {
    // Replace the narrower working directory first because it can be nested
    // beneath the selected project. Equal project/working paths also resolve
    // to the isolated project rather than the repository worktree root.
    prompt
        .replace(
            &source_working.display().to_string(),
            &isolated_working.display().to_string(),
        )
        .replace(
            &source_project.display().to_string(),
            &isolated_project.display().to_string(),
        )
}

fn is_complete_build_result(result: &SubAgentResult) -> bool {
    result.termination == SubAgentTermination::Completed
        && result.objective_status() == TaskObjectiveStatus::Complete
        && result.has_usable_evidence()
}

fn is_degraded_build_result(result: &SubAgentResult) -> bool {
    (result.termination.is_degraded_interruption()
        || matches!(
            result.objective_status(),
            TaskObjectiveStatus::Degraded | TaskObjectiveStatus::Blocked
        ))
        && result.has_usable_evidence()
}

fn is_cancelled_build_result(result: &SubAgentResult) -> bool {
    result.termination == SubAgentTermination::Cancelled
}

fn build_result_counts(results: &[SubAgentResult]) -> BuildResultCounts {
    let complete = results
        .iter()
        .filter(|result| is_complete_build_result(result))
        .count();
    let degraded = results
        .iter()
        .filter(|result| is_degraded_build_result(result))
        .count();
    let cancelled = results
        .iter()
        .filter(|result| is_cancelled_build_result(result))
        .count();
    let usable = complete.saturating_add(degraded);

    BuildResultCounts {
        complete,
        degraded,
        cancelled,
        usable,
        failed: results
            .len()
            .saturating_sub(usable.saturating_add(cancelled)),
    }
}

fn classify_build_outcome_with_handoff(
    results_len: usize,
    incomplete_builders: usize,
    modified_files: usize,
    has_active_process_handoff: bool,
) -> &'static str {
    if modified_files > 0 {
        return classify_build_outcome(results_len, incomplete_builders, modified_files);
    }
    if results_len > 0 && has_active_process_handoff {
        return if incomplete_builders == 0 {
            "success"
        } else {
            "partial"
        };
    }
    classify_build_outcome(results_len, incomplete_builders, modified_files)
}

fn build_confidence_with_handoff(
    failed_builders: usize,
    modified_files: usize,
    has_active_process_handoff: bool,
) -> &'static str {
    if modified_files > 0 {
        return build_confidence(failed_builders, modified_files);
    }
    if failed_builders == 0 && has_active_process_handoff {
        // Registry liveness proves that the process is controllable, but an
        // endpoint hint parsed from its command is not a readiness probe.
        return "medium";
    }
    build_confidence(failed_builders, modified_files)
}

fn build_summary_with_handoff(
    successful_builders: usize,
    degraded_builders: usize,
    cancelled_builders: usize,
    failed_builders: usize,
    modified_files: usize,
    lines_added: usize,
    lines_removed: usize,
    process_handoff: Option<&str>,
) -> String {
    let build_summary = build_investigation_summary(
        successful_builders,
        degraded_builders,
        cancelled_builders,
        failed_builders,
        modified_files,
        lines_added,
        lines_removed,
    );

    match (modified_files > 0, process_handoff) {
        (true, Some(handoff)) => format!(
            "{build_summary} Delegated build also handed off tracked process(es): {handoff}. Process liveness was revalidated at aggregation; endpoint readiness remains unverified."
        ),
        (false, Some(handoff)) => format!(
            "Delegated build handed off tracked process(es): {handoff}. Process liveness was revalidated at aggregation; endpoint readiness remains unverified."
        ),
        (_, None) => build_summary,
    }
}

fn structured_task_policy(
    task: &StructuredAgentTaskParams,
    ctx: &ToolContext,
    group_turn_budget: Option<usize>,
) -> DelegationPolicy {
    let capabilities = task
        .capabilities
        .iter()
        .map(|capability| AgentCapability::parse(capability))
        .collect::<Result<std::collections::BTreeSet<_>, _>>()
        .expect("structured Agent capabilities were normalized before execution");
    let max_turns = match (task.max_turns, group_turn_budget) {
        (Some(requested), Some(ceiling)) => Some(requested.min(ceiling)),
        (Some(requested), None) => Some(requested),
        (None, ceiling) => ceiling,
    };
    DelegationPolicy::for_subagent_child(
        ctx.permission_mode,
        max_turns,
        capabilities.contains(&AgentCapability::Read),
        capabilities.contains(&AgentCapability::Write),
        capabilities.contains(&AgentCapability::Execute),
    )
    .with_supervised_approval(ctx.supervised_approval_granted)
    .with_execution_tool_allowlist(ctx.execution_tool_allowlist.as_ref())
}

fn delegated_role_for_policy(policy: &DelegationPolicy) -> DelegatedRunRole {
    if !policy.read_only_only {
        DelegatedRunRole::Build
    } else if policy.bash_allowed {
        DelegatedRunRole::Verifier
    } else {
        DelegatedRunRole::Explore
    }
}

pub(super) fn build_execution_waves(
    tasks: &[SubAgentTask],
    structured: Option<&[StructuredAgentTaskParams]>,
) -> Vec<Vec<SubAgentTask>> {
    let Some(structured) = structured else {
        return vec![tasks.to_vec()];
    };
    let mut depths = std::collections::BTreeMap::<String, usize>::new();
    for task in structured {
        let depth = task
            .depends_on
            .iter()
            .filter_map(|dependency| depths.get(dependency))
            .max()
            .copied()
            .unwrap_or(0)
            + usize::from(!task.depends_on.is_empty());
        depths.insert(task.id.clone(), depth);
    }
    let max_depth = depths.values().copied().max().unwrap_or(0);
    (0..=max_depth)
        .map(|depth| {
            tasks
                .iter()
                .filter(|task| depths.get(&task.id).copied().unwrap_or(0) == depth)
                .cloned()
                .collect::<Vec<_>>()
        })
        .filter(|wave| !wave.is_empty())
        .collect()
}

pub(super) fn build_isolation_batches(
    tasks: &[SubAgentTask],
    structured: Option<&[StructuredAgentTaskParams]>,
    delegated_run_id: &str,
) -> Vec<(usize, String, Vec<String>)> {
    build_execution_waves(tasks, structured)
        .into_iter()
        .enumerate()
        .filter_map(|(wave_ordinal, wave)| {
            let task_ids = wave
                .into_iter()
                .filter(|task| {
                    task.delegation_policy
                        .as_ref()
                        .is_some_and(|policy| !policy.read_only_only)
                })
                .map(|task| task.id)
                .collect::<Vec<_>>();
            (task_ids.len() > 1).then(|| {
                (
                    wave_ordinal,
                    format!("{delegated_run_id}-wave-{wave_ordinal:04}"),
                    task_ids,
                )
            })
        })
        .collect()
}

async fn execute_builder_waves(
    pool: &SubAgentPool,
    waves: Vec<Vec<SubAgentTask>>,
    context: Arc<SharedBuildContext>,
    progress_tx: tokio::sync::mpsc::UnboundedSender<AgentProgress>,
    mut isolation: Vec<BuildIsolationSet>,
    project_dir: PathBuf,
    working_dir: PathBuf,
    coordinator: Option<&DelegationCoordinator>,
    delegation_group_id: &str,
    integration_owner: String,
    integration_workspace: String,
) -> Vec<SubAgentResult> {
    let mut all_results = Vec::new();
    for mut wave in waves {
        attach_direct_dependency_evidence(&mut wave, &all_results, &working_dir);
        let isolation_index = isolation.iter().position(|set| {
            set.workspaces()
                .iter()
                .any(|workspace| wave.iter().any(|task| task.id == workspace.task_id))
        });
        let wave_isolation = if let Some(index) = isolation_index {
            let prepared = isolation.remove(index);
            let batch_id = prepared.group_id().to_string();
            let task_ids = prepared.task_ids();
            if let Err(error) = prepared.discard().await {
                all_results.extend(durable_isolation_wave_failures(
                    &wave,
                    coordinator,
                    delegation_group_id,
                    format!(
                        "Isolated writer wave was not started because its stale workspace snapshot could not be retired: {error}"
                    ),
                ));
                continue;
            }
            let refreshed = match BuildIsolationSet::prepare(
                project_dir.clone(),
                working_dir.clone(),
                batch_id,
                task_ids,
            )
            .await
            {
                Ok(Some(isolation)) => isolation,
                Ok(None) => {
                    all_results.extend(durable_isolation_wave_failures(
                        &wave,
                        coordinator,
                        delegation_group_id,
                        "Isolated writer wave was not started because no attempt workspaces were materialized."
                            .to_string(),
                    ));
                    continue;
                }
                Err(error) => {
                    all_results.extend(durable_isolation_wave_failures(
                        &wave,
                        coordinator,
                        delegation_group_id,
                        format!(
                            "Isolated writer wave was not started because its current dependency snapshot could not be materialized: {error}"
                        ),
                    ));
                    continue;
                }
            };

            let mut contract_error = None;
            for workspace in refreshed.workspaces() {
                let Some(task) = wave.iter_mut().find(|task| task.id == workspace.task_id) else {
                    contract_error = Some(format!(
                        "Isolated workspace {} has no task in its ready wave",
                        workspace.task_id
                    ));
                    break;
                };
                task.working_dir = workspace.working_dir.clone();
                task.sandbox_root = Some(workspace.root.clone());
                task.command_environment = workspace.command_environment();
                if let (Some(coordinator), Some(delegation_task_id)) =
                    (coordinator, task.delegation_task_id.as_deref())
                {
                    match coordinator.refresh_isolated_task_baseline(
                        delegation_task_id,
                        &workspace.root,
                        &workspace.baseline_commit,
                    ) {
                        Ok(true) => {}
                        Ok(false) => {
                            contract_error = Some(format!(
                                "Durable isolated task {} disappeared before its ready wave",
                                task.id
                            ));
                            break;
                        }
                        Err(error) => {
                            contract_error = Some(format!(
                                "Durable isolated task {} could not adopt its current dependency snapshot: {error}",
                                task.id
                            ));
                            break;
                        }
                    }
                }
            }
            if let Some(error) = contract_error {
                let _ = refreshed.discard().await;
                all_results.extend(durable_isolation_wave_failures(
                    &wave,
                    coordinator,
                    delegation_group_id,
                    error,
                ));
                continue;
            }
            Some(refreshed)
        } else {
            None
        };

        let mut wave_results = pool
            .execute_builders(wave, context.clone(), progress_tx.clone())
            .await;
        if let Some(isolation_set) = wave_isolation {
            if let Some(integration_permit) = pool
                .acquire_integration_writer(
                    integration_owner.clone(),
                    integration_workspace.clone(),
                )
                .await
            {
                wave_results = isolation_set
                    .integrate_recording(wave_results, context.clone())
                    .await;
                let signal = if wave_results.iter().any(|result| !result.success) {
                    BackpressureSignal::Failed
                } else {
                    BackpressureSignal::Healthy
                };
                integration_permit.complete(signal);
            } else {
                for result in &mut wave_results {
                    result.success = false;
                    result.termination = SubAgentTermination::Cancelled;
                    result.error = Some(
                        "Isolated build integration was cancelled; recovery workspaces were retained."
                            .to_string(),
                    );
                }
            }

            if let Some(coordinator) = coordinator {
                let isolated_tasks = match coordinator.get_group(delegation_group_id) {
                    Ok(Some(group)) => group
                        .tasks
                        .into_iter()
                        .filter(|task| {
                            task.specification.writer_mode == DelegationWriterMode::Isolated
                        })
                        .map(|task| {
                            (
                                task.specification.delegation_task_id,
                                task.specification.task_key,
                            )
                        })
                        .collect::<Vec<_>>(),
                    Ok(None) => {
                        let error = format!(
                            "Durable delegation group {delegation_group_id} disappeared before isolated integration could be recorded"
                        );
                        tracing::error!(%error);
                        for result in &mut wave_results {
                            result.success = false;
                            result.termination = SubAgentTermination::Failed;
                            result.error = Some(error.clone());
                        }
                        Vec::new()
                    }
                    Err(error) => {
                        let error = format!(
                            "Could not load durable delegation group {delegation_group_id} after isolated integration: {error}"
                        );
                        tracing::error!(%error);
                        for result in &mut wave_results {
                            result.success = false;
                            result.termination = SubAgentTermination::Failed;
                            result.error = Some(error.clone());
                        }
                        Vec::new()
                    }
                };

                for (delegation_task_id, task_key) in isolated_tasks {
                    let Some(result_index) = wave_results
                        .iter()
                        .position(|result| result.task_id == task_key)
                    else {
                        continue;
                    };
                    let succeeded =
                        wave_results[result_index].is_eligible_for_isolated_integration();
                    let integration_error = wave_results[result_index].error.clone();
                    let update = coordinator.complete_task_integration(
                        &delegation_task_id,
                        succeeded,
                        integration_error.as_deref(),
                    );
                    if !matches!(update, Ok(true)) {
                        let error = match update {
                            Ok(false) => format!(
                                "Durable integration state for task {task_key} was not updated"
                            ),
                            Err(error) => format!(
                                "Could not record durable integration state for task {task_key}: {error}"
                            ),
                            Ok(true) => unreachable!(),
                        };
                        tracing::error!(%error);
                        let result = &mut wave_results[result_index];
                        result.success = false;
                        result.termination = SubAgentTermination::Failed;
                        result.error = Some(error);
                    }
                }
            }
        }
        all_results.extend(wave_results);
    }
    all_results
}

fn isolation_wave_failures(wave: &[SubAgentTask], error: String) -> Vec<SubAgentResult> {
    wave.iter()
        .map(|task| SubAgentResult {
            task_id: task.id.clone(),
            agent_name: task.name.clone(),
            delegated_run_id: task.delegated_run_id.clone(),
            success: false,
            output: String::new(),
            files_examined: Vec::new(),
            duration_ms: 0,
            turns_used: 0,
            error: Some(error.clone()),
            termination: SubAgentTermination::Failed,
            policy_violations: Vec::new(),
            evidence: Default::default(),
            background_processes: Vec::new(),
        })
        .collect()
}

fn durable_isolation_wave_failures(
    wave: &[SubAgentTask],
    coordinator: Option<&DelegationCoordinator>,
    delegation_group_id: &str,
    mut error: String,
) -> Vec<SubAgentResult> {
    if let Some(coordinator) = coordinator {
        let task_ids = wave
            .iter()
            .filter_map(|task| task.delegation_task_id.clone())
            .collect::<Vec<_>>();
        let durable = if task_ids.len() == wave.len() {
            coordinator.fail_unstarted_tasks(delegation_group_id, &task_ids, &error)
        } else {
            Err(anyhow::anyhow!(
                "isolated ready wave is missing durable task identities"
            ))
        };
        match durable {
            Ok(count) if count == wave.len() => {}
            Ok(count) => {
                error.push_str(&format!(
                    " Durable settlement recorded {count} of {} failed tasks.",
                    wave.len()
                ));
            }
            Err(durable_error) => {
                error.push_str(&format!(
                    " Durable pre-admission failure settlement also failed: {durable_error}"
                ));
            }
        }
    }
    isolation_wave_failures(wave, error)
}

impl AgentTool {
    // Build
    // -----------------------------------------------------------------------

    pub(super) async fn execute_build(&self, params: Params, ctx: &ToolContext) -> ToolResult {
        if ctx.project_dir.is_none() {
            return ToolResult::error(
                "No project directory is selected for this session. Create or choose a project directory, then promote the session before using build.",
            );
        }

        let evidence_kind = aggregate_evidence_kind(&params);

        let client = self.resolve_client(ctx);
        let workspace_scope = match delegated_workspace_scope(
            ctx.project_dir
                .as_deref()
                .expect("build checked project directory"),
        ) {
            Ok(scope) => scope,
            Err(error) => {
                return ToolResult::error_with_code("invalid_project_workspace", error);
            }
        };
        let selected_workspace_root = PathBuf::from(&workspace_scope.path);

        // Create shared build context
        let context = Arc::new(SharedBuildContext::new());

        // Merge conventions: project settings as base, user params override/extend
        let project_settings = ctx
            .project_dir
            .as_ref()
            .map(|p| ProjectSettings::load(p))
            .unwrap_or_default();
        let mut conventions = project_settings.conventions.unwrap_or_default();
        if let Some(user_conventions) = &params.conventions {
            conventions.extend(user_conventions.iter().cloned());
        }
        if !conventions.is_empty() {
            context.set_conventions(conventions);
        }

        // Adaptive scheduling starts every component eagerly. An explicit value
        // is a user ceiling, not a hidden product cap.
        let num_components = params
            .tasks
            .as_ref()
            .map(Vec::len)
            .or_else(|| params.components.as_ref().map(Vec::len))
            .unwrap_or(1);
        let concurrency = params.max_concurrency;

        // Build tasks - all use Opus for high-quality code generation
        let mut tasks: Vec<SubAgentTask> = Vec::new();
        let delegated_run_id = Uuid::new_v4().to_string();
        let capabilities = params
            .capabilities
            .iter()
            .map(|capability| AgentCapability::parse(capability))
            .collect::<Result<std::collections::BTreeSet<_>, _>>()
            .expect("AgentSpec validated parallel child capabilities");
        let delegation_policy = DelegationPolicy::for_subagent_child(
            ctx.permission_mode,
            params.max_turns,
            capabilities.contains(&AgentCapability::Read),
            capabilities.contains(&AgentCapability::Write),
            capabilities.contains(&AgentCapability::Execute),
        )
        .with_supervised_approval(ctx.supervised_approval_granted)
        .with_execution_tool_allowlist(ctx.execution_tool_allowlist.as_ref());
        let mut delegated_lease = open_delegated_run_store(ctx).map(DelegatedRunLease::new);
        let background = params.run_in_background.unwrap_or(false);
        if background && ctx.db_path.is_none() {
            return ToolResult::error_with_code(
                "agent_persistence_error",
                "Background build was not started because this session has no durable database.",
            );
        }
        if background && delegated_lease.is_none() {
            return ToolResult::error_with_code(
                "agent_persistence_error",
                "Background build was not started because its delegated-run database could not be opened.",
            );
        }
        if background && ctx.session_id.is_none() {
            return ToolResult::error_with_code(
                "agent_persistence_error",
                "Background build was not started because it has no durable parent session.",
            );
        }
        let mut target_scope = vec![workspace_scope.clone()];
        let parent_name = params.name.as_deref().unwrap_or("child");
        let project_context =
            build_subagent_project_instructions(&ctx.working_dir, ctx.project_dir.as_deref());

        if let Some(ref structured_tasks) = params.tasks {
            let total = structured_tasks.len();
            let graph_summary = structured_tasks
                .iter()
                .map(|task| {
                    let dependencies = if task.depends_on.is_empty() {
                        "ready immediately".to_string()
                    } else {
                        format!("after {}", task.depends_on.join(", "))
                    };
                    format!("  - {} ({dependencies})", task.id)
                })
                .collect::<Vec<_>>()
                .join("\n");
            for (index, structured) in structured_tasks.iter().enumerate() {
                let task_policy = structured_task_policy(structured, ctx, params.max_turns);
                let name = structured
                    .name
                    .as_deref()
                    .map(str::trim)
                    .filter(|name| !name.is_empty())
                    .unwrap_or(&structured.id)
                    .to_string();
                let dependencies = if structured.depends_on.is_empty() {
                    "None; this task is ready immediately.".to_string()
                } else {
                    structured.depends_on.join(", ")
                };
                let scope = structured.scope.as_deref().unwrap_or("project workspace");
                let write_intent = if structured.write_intent.is_empty() {
                    "No declared paths.".to_string()
                } else {
                    structured.write_intent.join(", ")
                };
                let expected_output = structured
                    .expected_output
                    .as_deref()
                    .map(|expected| format!("\nEXPECTED OUTPUT:\n{expected}\n"))
                    .unwrap_or_default();
                let acceptance_contract = acceptance_contract_block(&structured.acceptance_checks);
                let task_working_dir = match structured_task_working_dir(
                    ctx.project_dir
                        .as_deref()
                        .expect("build checked project directory"),
                    structured.working_dir.as_deref(),
                ) {
                    Ok(path) => path,
                    Err(error) => {
                        return ToolResult::error_with_code("invalid_agent_task_scope", error);
                    }
                };
                let task_project_context = build_subagent_project_instructions(
                    &task_working_dir,
                    ctx.project_dir.as_deref(),
                );
                let task_prompt = format!(
                    "You are task {} of {} in one coordinated Agent task graph.\n\n\
                     TASK ID: {}\nTASK NAME: {}\n\nTASK INSTRUCTIONS:\n{}\n{}\n\
                     GROUP OBJECTIVE:\n{}\n\nDEPENDENCIES:\n{}\n\nPRIMARY SCOPE:\n{}\n\n\
                     DECLARED WRITE INTENT:\n{}\n\n{}\n\nTASK GRAPH:\n{}\n\n\
                     Execute only this bounded task. Respect its exact capability policy. Return concrete evidence and validation for parent synthesis.",
                    index + 1,
                    total,
                    structured.id,
                    name,
                    structured.objective(),
                    expected_output,
                    params.prompt,
                    dependencies,
                    scope,
                    write_intent,
                    acceptance_contract,
                    graph_summary,
                );
                let mut task = SubAgentTask::new(structured.id.clone(), task_prompt)
                    .with_name(name.clone())
                    .with_identity(AgentIdentity::child(
                        structured.id.clone(),
                        "/root",
                        name.clone(),
                        match evidence_kind {
                            AggregateEvidenceKind::Build => "builder",
                            AggregateEvidenceKind::Report => "verifier",
                        },
                        index,
                    ))
                    .with_working_dir(task_working_dir)
                    .with_project_context(task_project_context)
                    .with_dependencies(structured.depends_on.clone())
                    .with_delegated_run_id(delegated_run_id.clone())
                    .with_delegation_policy(task_policy.clone())
                    .with_reasoning_effort(ctx.delegated_reasoning_effort)
                    .with_process_context(
                        ctx.process_registry.clone(),
                        ctx.user_id.clone(),
                        ctx.session_id.clone(),
                    )
                    .with_provider_call_trace(ctx.provider_call_trace.clone());
                task = task.with_sandbox_root(selected_workspace_root.clone());
                if let Some(max_turns) = task_policy.max_turns {
                    task = task.with_max_turns(max_turns);
                }
                target_scope.push(DelegatedRunScope {
                    label: name,
                    path: structured
                        .working_dir
                        .clone()
                        .unwrap_or_else(|| ".".to_string()),
                    kind: "task".to_string(),
                });
                tasks.push(task);
            }
        } else if let Some(ref components) = params.components {
            let total = components.len();
            let other_components: Vec<_> = components.iter().map(|c| c.as_str()).collect();

            // One agent per component - each gets their own file for TRUE parallelism
            for (i, component) in components.iter().enumerate() {
                let component_name = component.split_whitespace().next().unwrap_or("component");
                let name = format!("{parent_name} / {component_name}");
                let others: Vec<_> = other_components
                    .iter()
                    .enumerate()
                    .filter(|(j, _)| *j != i)
                    .map(|(j, c)| format!("  - Builder {}: {}", j, c))
                    .collect();

                // Create detailed prompt emphasizing SEPARATE FILES
                let task_prompt = format!(
                    "You are Builder {} of {} in a parallel build team.\n\n\
                     YOUR COMPONENT: {}\n\n\
                     OVERALL GOAL:\n{}\n\n\
                     OTHER BUILDERS (working in parallel):\n{}\n\n\
                     PARALLEL BUILD STRATEGY:\n\
                     1. Create YOUR OWN file(s) for your component - don't wait for others\n\
                     2. Name files clearly: {}_something.ext (e.g., game_engine.py, snake_logic.py)\n\
                     3. If you need to import from another builder's module, assume it exists\n\
                     4. Export clear interfaces (functions, classes) others can import\n\
                     5. At the end, if a main.py/main.rs is needed, Builder 0 creates it and imports all modules\n\n\
                     COORDINATION:\n\
                     - Check [SHARED TYPES] for interfaces other builders registered\n\
                     - Register YOUR public functions/classes so others can import them\n\
                     - File locks are automatic - but you shouldn't need them if using separate files\n\n\
                     {}\n\n\
                     BUILD YOUR COMPONENT NOW. Create your file(s) and implement fully.",
                    i, total,
                    component,
                    params.prompt,
                    if others.is_empty() { "  (none - you're solo)".to_string() } else { others.join("\n") },
                    component_name.to_lowercase().replace(' ', "_"),
                    acceptance_contract_block(&params.acceptance_checks),
                );

                let mut task = SubAgentTask::new(format!("builder-{}", i), task_prompt)
                    .with_name(name.clone())
                    .with_working_dir(ctx.working_dir.clone())
                    .with_project_context(project_context.clone())
                    .with_delegated_run_id(delegated_run_id.clone())
                    .with_delegation_policy(delegation_policy.clone())
                    .with_reasoning_effort(ctx.delegated_reasoning_effort)
                    .with_process_context(
                        ctx.process_registry.clone(),
                        ctx.user_id.clone(),
                        ctx.session_id.clone(),
                    )
                    .with_provider_call_trace(ctx.provider_call_trace.clone());
                task = task.with_sandbox_root(selected_workspace_root.clone());
                if let Some(max_turns) = params.max_turns {
                    task = task.with_max_turns(max_turns);
                }

                // Attach plan task ID if provided for auto-completion
                if let Some(ref task_ids) = params.task_ids {
                    if let Some(plan_task_id) = task_ids.get(i) {
                        task = task.with_plan_task_id(plan_task_id);
                    }
                }

                target_scope.push(DelegatedRunScope {
                    label: name,
                    path: component.clone(),
                    kind: "component".to_string(),
                });
                tasks.push(task);
            }
        } else {
            // Single builder for the whole task
            target_scope.push(DelegatedRunScope {
                label: "main".to_string(),
                path: ".".to_string(),
                kind: "project".to_string(),
            });
            let task_prompt = format!(
                "{}\n\n{}",
                params.prompt,
                acceptance_contract_block(&params.acceptance_checks)
            );
            let mut task = SubAgentTask::new("builder-main", task_prompt)
                .with_name("main")
                .with_working_dir(ctx.working_dir.clone())
                .with_project_context(project_context.clone())
                .with_delegated_run_id(delegated_run_id.clone())
                .with_delegation_policy(delegation_policy.clone())
                .with_reasoning_effort(ctx.delegated_reasoning_effort)
                .with_process_context(
                    ctx.process_registry.clone(),
                    ctx.user_id.clone(),
                    ctx.session_id.clone(),
                )
                .with_provider_call_trace(ctx.provider_call_trace.clone());
            task = task.with_sandbox_root(selected_workspace_root.clone());
            if let Some(max_turns) = params.max_turns {
                task = task.with_max_turns(max_turns);
            }
            tasks.push(task);
        }

        // Every ready wave with multiple writers receives its own isolation
        // batch. A dependency root may safely write the authoritative tree by
        // itself; a later engine/UI wave must not silently collapse to shared
        // writers merely because it was not ready at graph creation time.
        let isolation_batches =
            build_isolation_batches(&tasks, params.tasks.as_deref(), &delegated_run_id);
        let requires_isolation = !isolation_batches.is_empty();
        let mut materialization_guards = Vec::new();
        if requires_isolation {
            if let Some(db_path) = ctx.db_path.as_ref() {
                let coordinator = DelegationCoordinator::new(db_path.clone());
                match coordinator.get_group(&delegated_run_id) {
                    Ok(Some(_)) => {
                        return ToolResult::error_with_code(
                            "agent_persistence_error",
                            "Delegated build was not started because its durable group already exists.",
                        );
                    }
                    Ok(None) => {
                        // Ownership was checked once for the canonical graph;
                        // each deterministic wave batch is then guarded and
                        // cleaned independently.
                    }
                    Err(error) => {
                        return ToolResult::error_with_code(
                            "agent_persistence_error",
                            format!("Parallel builders could not check durable batch ownership: {error}"),
                        );
                    }
                }
            }
            for (_, batch_id, task_ids) in &isolation_batches {
                let guard = match BuildIsolationMaterializationGuard::acquire(batch_id.clone())
                    .await
                {
                    Ok(guard) => guard,
                    Err(error) => {
                        return ToolResult::error_with_code(
                            "agent_workspace_isolation_error",
                            format!(
                                "Parallel builders could not reserve isolated wave {batch_id}: {error}"
                            ),
                        );
                    }
                };
                if let Err(error) = guard
                    .remove_abandoned_preparation(
                        ctx.project_dir
                            .as_ref()
                            .expect("build checked project directory")
                            .clone(),
                        task_ids.len(),
                    )
                    .await
                {
                    return ToolResult::error_with_code(
                        "agent_workspace_isolation_error",
                        format!(
                            "Parallel builders found an ambiguous abandoned isolation wave and retained it for recovery: {error}"
                        ),
                    );
                }
                materialization_guards.push(guard);
            }
        }

        // Parallel writers execute in isolated workspaces captured from one
        // source snapshot. Established Git repositories use detached
        // worktrees; unborn and non-Git projects use a private snapshot repo.
        let mut build_isolation = Vec::new();
        for (_, batch_id, task_ids) in isolation_batches {
            match BuildIsolationSet::prepare(
                ctx.project_dir
                    .as_ref()
                    .expect("build checked project directory")
                    .clone(),
                ctx.working_dir.clone(),
                batch_id,
                task_ids,
            )
            .await
            {
                Ok(Some(isolation)) => build_isolation.push(isolation),
                Ok(None) => {}
                Err(error) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return ToolResult::error_with_code(
                        "agent_workspace_isolation_error",
                        format!(
                            "Parallel builders were not started because isolated workspaces could not be prepared: {error}"
                        ),
                    );
                }
            }
        }
        for isolation in &build_isolation {
            for task in &mut tasks {
                let Some(workspace) = isolation
                    .workspaces()
                    .iter()
                    .find(|workspace| workspace.task_id == task.id)
                else {
                    continue;
                };
                let source_project = ctx
                    .project_dir
                    .as_ref()
                    .expect("build checked project directory");
                task.prompt = rewrite_isolated_prompt_paths(
                    &task.prompt,
                    source_project,
                    &ctx.working_dir,
                    &workspace.project_dir,
                    &workspace.working_dir,
                );
                task.prompt.push_str(&format!(
                    "\n\n[ISOLATED WRITE WORKSPACE]\nAll writes and commands for this attempt must remain under {}. The authoritative source workspace is unchanged until parent synthesis applies your patch.\n[/ISOLATED WRITE WORKSPACE]",
                    workspace.root.display()
                ));
                task.working_dir = workspace.working_dir.clone();
                task.sandbox_root = Some(workspace.root.clone());
                task.command_environment = workspace.command_environment();
            }
        }

        // A detached graph is not admitted until every immutable replay
        // envelope has been built successfully. In particular, do not create
        // a wakeable compatibility run and then discover that one dependent
        // task has an invalid working directory: that turns an ordinary
        // caller error into a ghost cancelled child completion.
        let resolved_model = client.resolved_model().wire_model_id.clone();
        let detached_executor_envelopes = if background {
            let envelopes = tasks
                .iter()
                .enumerate()
                .map(|(index, task)| {
                    let task_policy = task
                        .delegation_policy
                        .clone()
                        .unwrap_or_else(|| delegation_policy.clone());
                    let task_role = delegated_role_for_policy(&task_policy);
                    let executor_kind = match task_role {
                        DelegatedRunRole::Build => DelegationExecutorKind::Build,
                        DelegatedRunRole::Verifier => DelegationExecutorKind::Verify,
                        DelegatedRunRole::Planner => DelegationExecutorKind::Plan,
                        DelegatedRunRole::Explore => DelegationExecutorKind::Explore,
                    };
                    let delegation_task_id = format!("{delegated_run_id}:task:{index}");
                    build_detached_executor_envelope(
                        ctx,
                        &delegation_task_id,
                        &task.name,
                        &task.prompt,
                        executor_kind,
                        task_role,
                        &client.resolved_model().key,
                        &resolved_model,
                        &task.working_dir,
                        task.sandbox_root.as_deref().unwrap_or(&task.working_dir),
                    )
                    .map(Some)
                    .map_err(|error| {
                        format!(
                            "Detached Agent task '{}' was not admitted: {error}. Correct its explicit working_dir or omit working_dir to use the selected workspace; do not resume because no task graph was created.",
                            task.id
                        )
                    })
                })
                .collect::<Result<Vec<_>, _>>();
            match envelopes {
                Ok(envelopes) => envelopes,
                Err(error) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return ToolResult::error_with_recovery(
                        "agent_admission_error",
                        error,
                        false,
                        "Correct the rejected task specification and spawn one new graph. No delegated run was admitted.",
                        vec![
                            "Do not call resume or status for this failed launch; no graph exists."
                                .to_string(),
                            "Do not repeat the same rejected spawn unchanged.".to_string(),
                        ],
                        Some(serde_json::json!({
                            "admitted": false,
                            "safe_alternative": "omit task working_dir to use the selected workspace"
                        })),
                    );
                }
            }
        } else {
            vec![None; tasks.len()]
        };

        let durable_run_started = if let (Some(lease), Some(session_id)) =
            (delegated_lease.as_mut(), ctx.session_id.as_ref())
        {
            let start = DelegatedRunStartInput {
                delegated_run_id: delegated_run_id.clone(),
                parent_session_id: session_id.clone(),
                parent_tool_call_id: ctx.tool_use_id.clone(),
                role: DelegatedRunRole::Build,
                stage: DelegatedRunStage::Created,
                provider: Some(client.provider_id().to_string()),
                model: Some(client.config().model.clone()),
                resumable: true,
                resumed_from_run_id: params.resumed_from_run_id.clone(),
                target_scope: target_scope.clone(),
            };
            let create = if background {
                lease.create_background_run_with_child_contract(
                    &start,
                    Some(parent_name),
                    &capabilities,
                )
            } else {
                lease.create_run_with_child_contract(&start, Some(parent_name), &capabilities)
            };
            match create {
                Ok(DelegatedRunCreateOutcome::Created) => {}
                Ok(DelegatedRunCreateOutcome::ExistingContinuation {
                    delegated_run_id,
                    resumed_from_run_id,
                }) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return existing_continuation_error(&resumed_from_run_id, &delegated_run_id);
                }
                Ok(DelegatedRunCreateOutcome::ExistingActiveWorkspaceWriter {
                    delegated_run_id: active_run_id,
                    workspace_path,
                }) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return ToolResult::error_with_recovery(
                        "agent_active_workspace_writer",
                        format!(
                            "A write-capable Agent graph is already active for workspace '{workspace_path}' (delegated run {active_run_id}). A second writer graph was not admitted."
                        ),
                        true,
                        "Use Agent status or wait on the active delegated run. Interrupt it explicitly before starting a replacement graph.",
                        vec![
                            format!("Continue with delegated_run_id '{active_run_id}' instead of spawning a duplicate graph."),
                            "Do not retry spawn with a new tool-call id while the active graph is live.".to_string(),
                        ],
                        Some(serde_json::json!({
                            "admitted": false,
                            "active_delegated_run_id": active_run_id,
                            "workspace_path": workspace_path,
                        })),
                    );
                }
                Err(error) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return ToolResult::error_with_code(
                        "agent_persistence_error",
                        format!(
                            "Delegated build was not started because its durable run record could not be created: {error}"
                        ),
                    );
                }
            }
            true
        } else {
            false
        };
        if background && !durable_run_started {
            discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
            return ToolResult::error_with_code(
                "agent_persistence_error",
                "Background build was not started because durable run creation was unavailable.",
            );
        }

        // Establish the parent-owned group only after its compatibility run
        // exists. Older clients continue to consume that aggregate run while
        // every component now executes under a distinct durable logical task.
        let mut delegation_coordinator = None;
        if durable_run_started && !tasks.is_empty() {
            let db_path = ctx
                .db_path
                .as_ref()
                .expect("durable delegated build has a database path");
            let session_id = ctx
                .session_id
                .as_ref()
                .expect("durable delegated build has a parent session");
            let coordinator = DelegationCoordinator::new(db_path.clone());
            let task_specs = match tasks
                .iter()
                .enumerate()
                .map(|(index, task)| {
                    let isolated = build_isolation.iter().find_map(|isolation| {
                        isolation
                            .workspaces()
                            .iter()
                            .find(|workspace| workspace.task_id == task.id)
                    });
                    let delegation_task_id = format!("{delegated_run_id}:task:{index}");
                    let structured = params
                        .tasks
                        .as_ref()
                        .and_then(|tasks| tasks.iter().find(|candidate| candidate.id == task.id));
                    let task_policy = task
                        .delegation_policy
                        .clone()
                        .unwrap_or_else(|| delegation_policy.clone());
                    let task_role = delegated_role_for_policy(&task_policy);
                    let executor_envelope = detached_executor_envelopes[index].clone();
                    Ok::<_, String>(DelegationTaskSpec {
                        delegation_task_id,
                        task_key: task.id.clone(),
                        objective: task.prompt.clone(),
                        role: task_role,
                        target_scope: vec![
                            workspace_scope.clone(),
                            DelegatedRunScope {
                                label: task.name.clone(),
                                path: task.id.clone(),
                                kind: "component".to_string(),
                            },
                        ],
                        max_attempts: 2,
                        depends_on: structured
                            .map(|task| task.depends_on.clone())
                            .unwrap_or_default(),
                        write_intent: structured
                            .map(|task| task.write_intent.clone())
                            .unwrap_or_default(),
                        task_policy: Some(task_policy),
                        writer_mode: if isolated.is_some() {
                            DelegationWriterMode::Isolated
                        } else {
                            DelegationWriterMode::Shared
                        },
                        attempt_workspace: isolated
                            .map(|workspace| workspace.root.display().to_string()),
                        workspace_baseline: isolated
                            .map(|workspace| workspace.baseline_commit.clone()),
                        executor_envelope,
                    })
                })
                .collect::<Result<Vec<_>, _>>()
            {
                Ok(specifications) => specifications,
                Err(error) => {
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                    return ToolResult::error_with_code("agent_persistence_error", error);
                }
            };
            let group_input = DelegationGroupStartInput {
                delegation_group_id: delegated_run_id.clone(),
                parent_session_id: session_id.clone(),
                parent_tool_call_id: ctx.tool_use_id.clone(),
                contract: DelegationGroupContract {
                    execution_mode: if background {
                        DelegationExecutionMode::Detached
                    } else {
                        DelegationExecutionMode::Foreground
                    },
                    completion_policy: DelegationCompletionPolicy::AllSettled,
                    failure_policy: DelegationFailurePolicy::Continue,
                    governance: DelegationGovernance {
                        permission_mode: ctx.permission_mode,
                        reasoning_effort: ctx.delegated_reasoning_effort,
                        delegated_turn_budget: params.max_turns,
                        max_parallelism: concurrency.unwrap_or(tasks.len()).max(1).min(tasks.len()),
                        execution_tool_allowlist: delegation_policy
                            .execution_tool_allowlist
                            .clone(),
                        delegation_policy: delegation_policy.clone(),
                    },
                },
                tasks: task_specs.clone(),
            };
            if let Err(error) = coordinator.create_group(&group_input) {
                if matches!(coordinator.get_group(&delegated_run_id), Ok(None)) {
                    if let Some(lease) = delegated_lease.as_mut() {
                        if let Err(discard_error) = lease.discard_unadmitted_run(&delegated_run_id)
                        {
                            tracing::error!(
                                delegated_run_id,
                                %discard_error,
                                "Failed to discard an unadmitted compatibility run"
                            );
                        }
                    }
                    discard_unowned_build_isolation(&mut build_isolation, &delegated_run_id).await;
                }
                return ToolResult::error_with_code(
                    "agent_persistence_error",
                    format!(
                        "Delegated build was not started because its durable group could not be created: {error}"
                    ),
                );
            }
            for (task, specification) in tasks.iter_mut().zip(task_specs) {
                *task = task.clone().with_delegation_task(
                    delegated_run_id.clone(),
                    specification.delegation_task_id,
                );
                if task.max_turns_override.is_none() {
                    task.max_turns_override = params.max_turns;
                }
            }
            delegation_coordinator = Some(coordinator);
        }
        drop(materialization_guards);

        info!("Agent tool (build): Created {} builder tasks", tasks.len());
        for (i, task) in tasks.iter().enumerate() {
            debug!("Builder {}: id={}, name={}", i, task.id, task.name);
        }

        // Create one cancellation root and one broadcast mailbox per background run.
        let (pool_cancellation, background_runtime_registration, background_host_cancellation) =
            if background {
                let run_cancellation = self.cancellation.child_token();
                let (first_mailbox, runtime_registration) = self.runtime.register_guarded(
                    delegated_run_id.clone(),
                    params.name.as_deref().unwrap_or("build"),
                    ctx.session_id.clone(),
                    run_cancellation.clone(),
                );
                for (index, task) in tasks.iter_mut().enumerate() {
                    let mailbox = if index == 0 {
                        first_mailbox.clone()
                    } else {
                        self.runtime
                            .subscribe(&delegated_run_id)
                            .expect("registered build runtime")
                    };
                    *task = task.clone().with_mailbox(mailbox);
                }
                (
                    AgentCancellation::from_token(run_cancellation.clone()),
                    Some(runtime_registration),
                    Some(run_cancellation),
                )
            } else {
                let cancellation = ctx
                    .execution_cancellation
                    .clone()
                    .map(AgentCancellation::from_token)
                    .unwrap_or_else(|| self.cancellation.clone());
                (cancellation, None, None)
            };

        // Create pool and execute with build context
        let mut pool = SubAgentPool::new(client, pool_cancellation)
            .with_override_model(ctx.current_model.clone());
        if let Some(ceiling) = concurrency {
            pool = pool.with_concurrency(ceiling);
        }
        if let Some(coordinator) = delegation_coordinator.clone() {
            pool = pool.with_delegation_coordinator(coordinator);
        }
        let execution_waves = build_execution_waves(&tasks, params.tasks.as_deref());

        info!(
            "Agent tool (build): Starting adaptive builder pool with concurrency_ceiling={:?} (components={}), background={}",
            concurrency, num_components, params.run_in_background.unwrap_or(false)
        );

        // ── Background mode ──────────────────────────────────────────
        if background {
            let bg_delegated_run_id = delegated_run_id.clone();
            let bg_db_path = ctx.db_path.clone();
            let bg_session_id = ctx.session_id.clone();
            let bg_user_id = ctx.user_id.clone();
            let bg_workspace_root = ctx.filesystem_access_root();
            let bg_child_name = params.name.clone().unwrap_or_else(|| "child".to_string());
            let bg_delegation_policy = delegation_policy.clone();
            let bg_process_registry = ctx.process_registry.clone();
            let bg_process_owner_id = ctx.user_id.clone();
            let bg_group_coordinator = delegation_coordinator.clone();
            let mut bg_build_isolation = std::mem::take(&mut build_isolation);
            let bg_isolation_project_dir = ctx
                .project_dir
                .clone()
                .expect("build checked project directory");
            let bg_isolation_working_dir = ctx.working_dir.clone();
            let bg_execution_waves = execution_waves.clone();
            let bg_integration_workspace = workspace_scope.path.clone();
            let mut bg_runtime_registration = background_runtime_registration
                .expect("background build registered live runtime ownership");
            let progress_tx = ctx.agent_progress_tx.clone();
            let bg_runtime = self.runtime.clone();
            let mut bg_run_lease = delegated_lease
                .take()
                .expect("background build start has an armed durable lease");
            let bg_host_heartbeat = match bg_run_lease.start_background_host_heartbeat(
                &bg_delegated_run_id,
                background_host_cancellation
                    .expect("background build has an execution cancellation token"),
            ) {
                Ok(heartbeat) => heartbeat,
                Err(error) => {
                    discard_unowned_build_isolation(&mut bg_build_isolation, &bg_delegated_run_id)
                        .await;
                    return ToolResult::error_with_code(
                        "agent_persistence_error",
                        format!(
                            "Background build was not started because its durable host lease could not start: {error}"
                        ),
                    );
                }
            };

            tokio::spawn(async move {
                let _bg_host_heartbeat = bg_host_heartbeat;
                // Keep a clone for the completion event after execute_builders consumes the tx
                let completion_tx = progress_tx.clone();

                let progress_tx = progress_tx.unwrap_or_else(|| {
                    let (tx, _rx) = tokio::sync::mpsc::unbounded_channel();
                    tx
                });
                let mut results = execute_builder_waves(
                    &pool,
                    bg_execution_waves,
                    context.clone(),
                    progress_tx,
                    std::mem::take(&mut bg_build_isolation),
                    bg_isolation_project_dir,
                    bg_isolation_working_dir,
                    bg_group_coordinator.as_ref(),
                    &bg_delegated_run_id,
                    bg_session_id
                        .clone()
                        .unwrap_or_else(|| bg_delegated_run_id.clone()),
                    bg_integration_workspace,
                )
                .await;
                let synthesis_permit = if let Some(coordinator) = bg_group_coordinator.as_ref() {
                    match coordinator.begin_synthesis(&bg_delegated_run_id) {
                        Ok(permit) => Some(permit),
                        Err(error) => match coordinator.get_group(&bg_delegated_run_id) {
                            Ok(Some(group)) if group.state.is_terminal() => {
                                tracing::info!(
                                    delegated_run_id = %bg_delegated_run_id,
                                    state = ?group.state,
                                    "Publishing truthful background aggregate for an already-terminal delegation group"
                                );
                                None
                            }
                            _ => {
                                tracing::error!(
                                    delegated_run_id = %bg_delegated_run_id,
                                    %error,
                                    "Stopping background aggregate because durable synthesis ownership was not acquired"
                                );
                                return;
                            }
                        },
                    }
                } else {
                    None
                };
                if synthesis_permit
                    .as_ref()
                    .is_some_and(|permit| permit.cancellation().is_cancelled())
                {
                    tracing::warn!(
                        delegated_run_id = %bg_delegated_run_id,
                        "Stopping background integration after durable synthesis ownership was lost"
                    );
                    return;
                }
                if synthesis_permit
                    .as_ref()
                    .is_some_and(|permit| permit.cancellation().is_cancelled())
                {
                    tracing::warn!(
                        delegated_run_id = %bg_delegated_run_id,
                        "Suppressing background aggregate publication after synthesis lease loss"
                    );
                    return;
                }

                for result in &mut results {
                    revalidate_background_processes(
                        &mut result.background_processes,
                        bg_process_registry.as_deref(),
                        bg_process_owner_id.as_deref(),
                    )
                    .await;
                }

                // Build the finalization payload (same logic as synchronous path)
                let stats = context.stats();
                let mut all_files: Vec<String> = Vec::new();
                let mut total_turns = 0;
                let mut total_duration_ms = 0u64;
                let mut errors: Vec<String> = Vec::new();
                let mut degradations: Vec<String> = Vec::new();
                let mut cancellations: Vec<String> = Vec::new();
                let mut builders = Vec::new();
                let mut background_processes = Vec::new();

                for result in &results {
                    builders.push(result.evidence_json());
                    background_processes.extend(result.background_processes.iter().cloned());
                    if is_cancelled_build_result(result) {
                        cancellations.push(format!("{}: cancelled", result.task_id));
                    } else if is_degraded_build_result(result) {
                        degradations.push(format!(
                            "{}: {}",
                            result.task_id,
                            result.outcome_reason()
                        ));
                    } else if !is_complete_build_result(result) {
                        errors.push(format!(
                            "{}: {}",
                            result.task_id,
                            result.error.as_deref().unwrap_or(result.outcome_reason())
                        ));
                    }
                    all_files.extend(result.files_examined.clone());
                    total_turns += result.turns_used;
                    total_duration_ms += result.duration_ms;
                }
                deduplicate_background_processes(&mut background_processes);

                let mut unique_files = Vec::new();
                for file in all_files {
                    if !unique_files.iter().any(|existing| existing == &file) {
                        unique_files.push(file);
                    }
                }

                let counts = build_result_counts(&results);
                let process_handoff = active_process_handoff_summary(&background_processes);
                let outcome = aggregate_outcome(
                    evidence_kind,
                    results.len(),
                    counts,
                    stats.files_modified,
                    process_handoff.is_some(),
                );
                let confidence = aggregate_confidence(
                    evidence_kind,
                    counts,
                    stats.files_modified,
                    process_handoff.is_some(),
                );
                let outcome_reason = aggregate_outcome_reason(
                    evidence_kind,
                    counts,
                    stats.files_modified,
                    process_handoff.is_some(),
                );
                let investigation_summary = aggregate_summary(
                    evidence_kind,
                    counts,
                    stats.files_modified,
                    stats.lines_added,
                    stats.lines_removed,
                    process_handoff.as_deref(),
                );
                let coverage_issues = errors
                    .iter()
                    .chain(degradations.iter())
                    .chain(cancellations.iter())
                    .cloned()
                    .collect::<Vec<_>>();
                let coverage_gap_notice = build_coverage_gap_notice(&coverage_issues);

                let payload = json!({
                    "delegated_run_id": bg_delegated_run_id,
                    "message": match evidence_kind {
                        AggregateEvidenceKind::Build => format!(
                            "Delegated build settled: {} builders, {} turns, +{} -{} lines across {} files",
                            results.len(), total_turns, stats.lines_added, stats.lines_removed, stats.files_modified,
                        ),
                        AggregateEvidenceKind::Report => format!(
                            "Delegated investigation settled: {} agents produced report evidence in {} turns",
                            results.len(), total_turns,
                        ),
                    },
                    "evidence_kind": match evidence_kind { AggregateEvidenceKind::Build => "build", AggregateEvidenceKind::Report => "report" },
                    "investigation_summary": investigation_summary,
                    "outcome": outcome,
                    "outcome_reason": outcome_reason,
                    "confidence": confidence,
                    "builder_count": if evidence_kind == AggregateEvidenceKind::Build { results.len() } else { 0 },
                    "report_count": if evidence_kind == AggregateEvidenceKind::Report { results.len() } else { 0 },
                    "agent_count": results.len(),
                    "successful_agents": counts.complete,
                    "usable_agents": counts.usable,
                    "degraded_agents": counts.degraded,
                    "cancelled_agents": counts.cancelled,
                    "failed_agents": counts.failed,
                    "total_turns": total_turns,
                    "total_duration_ms": total_duration_ms,
                    "files_examined": unique_files,
                    "agents": builders.clone(),
                    "builders": if evidence_kind == AggregateEvidenceKind::Build { builders.clone() } else { Vec::new() },
                    "reports": if evidence_kind == AggregateEvidenceKind::Report { builders } else { Vec::new() },
                    "background_processes": background_processes,
                    "lines_added": stats.lines_added,
                    "lines_removed": stats.lines_removed,
                    "files_modified": stats.files_modified,
                    "coverage_gap_notice": coverage_gap_notice,
                    "degradations": degradations,
                    "cancellations": cancellations,
                    "errors": errors,
                    "delegation_policy": bg_delegation_policy.audit_json(),
                });

                let final_stage = match outcome {
                    "success" => DelegatedRunStage::Complete,
                    "partial" => DelegatedRunStage::Degraded,
                    "cancelled" => DelegatedRunStage::Cancelled,
                    _ => DelegatedRunStage::Failed,
                };
                let finalization = persist_background_delegated_artifact(
                    &bg_run_lease,
                    &bg_delegated_run_id,
                    final_stage,
                    &payload,
                    &investigation_summary,
                    true,
                );

                match finalization {
                    Ok(authoritative) => {
                        if let Some(synthesis_permit) = synthesis_permit {
                            let group_state = group_terminal_state(authoritative.stage);
                            if let Err(error) = synthesis_permit.finalize(group_state) {
                                tracing::error!(
                                    delegated_run_id = %bg_delegated_run_id,
                                    %error,
                                    "Suppressing background parent wake because delegation group finalization failed"
                                );
                                return;
                            }
                        }
                        bg_run_lease.disarm(&bg_delegated_run_id);
                        let build_success = authoritative.stage == DelegatedRunStage::Complete;
                        let authoritative_summary = authoritative
                            .human_review
                            .as_deref()
                            .unwrap_or(&investigation_summary);
                        if let Some(ref tx) = completion_tx {
                            let (status, current_action) =
                                agent_progress_for_terminal_stage(authoritative.stage);
                            if tx
                                .send(AgentProgress {
                                    delegated_run_id: Some(bg_delegated_run_id.clone()),
                                    task_id: bg_child_name.clone(),
                                    name: bg_child_name.clone(),
                                    identity: None,
                                    status,
                                    tool_count: 0,
                                    tokens: 0,
                                    current_action,
                                    completion_summary: Some(authoritative_summary.to_string()),
                                    lines_added: stats.lines_added,
                                    lines_removed: stats.lines_removed,
                                    completed_plan_task: None,
                                    conversation_event: None,
                                })
                                .is_err()
                            {
                                debug!("Background build progress channel disconnected (parent returned)");
                            }
                        }
                        if authoritative.stage != DelegatedRunStage::Cancelled {
                            if let Err(error) = notify_child_completion(
                                &bg_runtime,
                                bg_db_path.as_deref(),
                                bg_session_id.as_deref(),
                                bg_user_id.as_deref(),
                                bg_workspace_root.as_deref(),
                                &bg_delegated_run_id,
                                &bg_child_name,
                                build_success,
                                authoritative_summary,
                            ) {
                                warn!(
                                    delegated_run_id = %bg_delegated_run_id,
                                    %error,
                                    "Failed to queue background child completion"
                                );
                                let _ = bg_runtime
                                    .request_completion_reconciliation(bg_delegated_run_id.clone());
                            }
                        }
                        bg_runtime_registration.finish(build_success);
                    }
                    Err(error) => {
                        tracing::error!(
                            delegated_run_id = %bg_delegated_run_id,
                            %error,
                            "Suppressing background build completion because terminal finalization was not authoritative"
                        );
                        // Guard Drop schedules abnormal durable reconciliation.
                    }
                }
            });

            return background_started_result(
                &delegated_run_id,
                params.name.as_deref().unwrap_or("child"),
                params.name.as_deref(),
            );
        }

        // ── Synchronous mode (existing behavior) ─────────────────────

        // Execute builders with progress channel if available
        let progress_tx = ctx.agent_progress_tx.clone().unwrap_or_else(|| {
            let (tx, _rx) = tokio::sync::mpsc::unbounded_channel();
            tx
        });
        let mut results = execute_builder_waves(
            &pool,
            execution_waves,
            context.clone(),
            progress_tx,
            std::mem::take(&mut build_isolation),
            ctx.project_dir
                .clone()
                .expect("build checked project directory"),
            ctx.working_dir.clone(),
            delegation_coordinator.as_ref(),
            &delegated_run_id,
            ctx.session_id
                .clone()
                .unwrap_or_else(|| delegated_run_id.clone()),
            workspace_scope.path.clone(),
        )
        .await;
        let synthesis_permit = if let Some(coordinator) = delegation_coordinator.as_ref() {
            match coordinator.begin_synthesis(&delegated_run_id) {
                Ok(permit) => Some(permit),
                Err(error) => match coordinator.get_group(&delegated_run_id) {
                    Ok(Some(group)) if group.state.is_terminal() => {
                        tracing::info!(
                            delegated_run_id = %delegated_run_id,
                            state = ?group.state,
                            "Publishing truthful foreground aggregate for an already-terminal delegation group"
                        );
                        None
                    }
                    _ => {
                        return ToolResult::error_with_code(
                            "agent_delegation_synthesis_busy",
                            format!("Delegation synthesis could not be claimed: {error}"),
                        );
                    }
                },
            }
        } else {
            None
        };
        if synthesis_permit
            .as_ref()
            .is_some_and(|permit| permit.cancellation().is_cancelled())
        {
            return ToolResult::error_with_code(
                "agent_delegation_synthesis_lost",
                "Delegation synthesis ownership was lost before build integration; recovery workspaces were retained.",
            );
        }
        if synthesis_permit
            .as_ref()
            .is_some_and(|permit| permit.cancellation().is_cancelled())
        {
            return ToolResult::error_with_code(
                "agent_delegation_synthesis_lost",
                "Delegation synthesis ownership was lost before aggregate publication; inspect the retained integration marker/workspaces.",
            );
        }

        for result in &mut results {
            revalidate_background_processes(
                &mut result.background_processes,
                ctx.process_registry.as_deref(),
                ctx.user_id.as_deref(),
            )
            .await;
        }

        info!(
            "Agent tool (build): Builder pool returned {} results",
            results.len()
        );

        // Get final stats from context
        let stats = context.stats();

        let mut all_files: Vec<String> = Vec::new();
        let mut total_turns = 0;
        let mut total_duration_ms = 0u64;
        let mut errors: Vec<String> = Vec::new();
        let mut degradations: Vec<String> = Vec::new();
        let mut cancellations: Vec<String> = Vec::new();
        let mut builders = Vec::new();
        let mut background_processes = Vec::new();

        for result in &results {
            builders.push(result.evidence_json());
            background_processes.extend(result.background_processes.iter().cloned());

            if is_cancelled_build_result(result) {
                cancellations.push(format!("{}: cancelled", result.task_id));
            } else if is_degraded_build_result(result) {
                degradations.push(format!("{}: {}", result.task_id, result.outcome_reason()));
            } else if !is_complete_build_result(result) {
                errors.push(format!(
                    "{}: {}",
                    result.task_id,
                    result.error.as_deref().unwrap_or(result.outcome_reason())
                ));
            }

            all_files.extend(result.files_examined.clone());
            total_turns += result.turns_used;
            total_duration_ms += result.duration_ms;
        }
        deduplicate_background_processes(&mut background_processes);

        let mut unique_files = Vec::new();
        for file in all_files {
            if !unique_files.iter().any(|existing| existing == &file) {
                unique_files.push(file);
            }
        }

        let message = match evidence_kind {
            AggregateEvidenceKind::Build => format!(
                "Delegated build settled: {} builders, {} turns, +{} -{} lines across {} files",
                results.len(),
                total_turns,
                stats.lines_added,
                stats.lines_removed,
                stats.files_modified,
            ),
            AggregateEvidenceKind::Report => format!(
                "Delegated investigation settled: {} agents produced report evidence in {} turns",
                results.len(),
                total_turns
            ),
        };
        let counts = build_result_counts(&results);
        let process_handoff = active_process_handoff_summary(&background_processes);
        let outcome = aggregate_outcome(
            evidence_kind,
            results.len(),
            counts,
            stats.files_modified,
            process_handoff.is_some(),
        );
        let confidence = aggregate_confidence(
            evidence_kind,
            counts,
            stats.files_modified,
            process_handoff.is_some(),
        );
        let outcome_reason = aggregate_outcome_reason(
            evidence_kind,
            counts,
            stats.files_modified,
            process_handoff.is_some(),
        );
        let investigation_summary = aggregate_summary(
            evidence_kind,
            counts,
            stats.files_modified,
            stats.lines_added,
            stats.lines_removed,
            process_handoff.as_deref(),
        );
        let coverage_issues = errors
            .iter()
            .chain(degradations.iter())
            .chain(cancellations.iter())
            .cloned()
            .collect::<Vec<_>>();
        let coverage_gap_notice = build_coverage_gap_notice(&coverage_issues);

        let high_contention_files = stats
            .high_contention_files
            .iter()
            .map(|(path, duration)| {
                json!({
                    "file": path.display().to_string(),
                    "wait_secs": duration.as_secs_f64(),
                })
            })
            .collect::<Vec<_>>();

        let payload = json!({
            "delegated_run_id": delegated_run_id,
            "message": message,
            "evidence_kind": match evidence_kind { AggregateEvidenceKind::Build => "build", AggregateEvidenceKind::Report => "report" },
            "investigation_summary": investigation_summary,
            "confidence": confidence,
            "outcome": outcome,
            "outcome_reason": outcome_reason,
            "builder_count": if evidence_kind == AggregateEvidenceKind::Build { results.len() } else { 0 },
            "report_count": if evidence_kind == AggregateEvidenceKind::Report { results.len() } else { 0 },
            "agent_count": results.len(),
            "successful_agents": counts.complete,
            "usable_agents": counts.usable,
            "degraded_agents": counts.degraded,
            "cancelled_agents": counts.cancelled,
            "failed_agents": counts.failed,
            "total_turns": total_turns,
            "total_duration_ms": total_duration_ms,
            "paths_examined": unique_files,
            "paths_examined_count": unique_files.len(),
            "files_examined": unique_files,
            "agents": builders.clone(),
            "builders": if evidence_kind == AggregateEvidenceKind::Build { builders.clone() } else { Vec::new() },
            "reports": if evidence_kind == AggregateEvidenceKind::Report { builders } else { Vec::new() },
            "background_processes": background_processes,
            "lines_added": stats.lines_added,
            "lines_removed": stats.lines_removed,
            "files_modified": stats.files_modified,
            "lock_contentions": stats.lock_contentions,
            "total_lock_wait_ms": stats.total_lock_wait_ms,
            "high_contention_files": high_contention_files,
            "coverage_gap_notice": coverage_gap_notice,
            "degradations": degradations,
            "cancellations": cancellations,
            "errors": errors,
            "delegation_policy": delegation_policy.audit_json(),
        });

        if durable_run_started {
            let lease = delegated_lease
                .as_mut()
                .expect("durable build start has an open store");
            let final_stage = match outcome {
                "success" => DelegatedRunStage::Complete,
                "partial" => DelegatedRunStage::Degraded,
                "cancelled" => DelegatedRunStage::Cancelled,
                _ => DelegatedRunStage::Failed,
            };
            let authoritative = match persist_delegated_artifact(
                lease,
                &delegated_run_id,
                final_stage,
                &payload,
                &investigation_summary,
                true,
            ) {
                Ok(authoritative) => authoritative,
                Err(error) => {
                    return delegated_persistence_error(&delegated_run_id, payload, &error);
                }
            };
            lease.disarm(&delegated_run_id);
            if let Some(synthesis_permit) = synthesis_permit {
                if let Err(error) =
                    synthesis_permit.finalize(group_terminal_state(authoritative.stage))
                {
                    return delegated_persistence_error(&delegated_run_id, payload, &error);
                }
            }
            // Individual builders finish before the aggregate artifact does.
            // Re-emit one authoritative aggregate boundary after persistence
            // so the foreground card cannot be stranded in Running.
            if let Some(ref tx) = ctx.agent_progress_tx {
                let (status, current_action) =
                    agent_progress_for_terminal_stage(authoritative.stage);
                let _ = tx.send(AgentProgress {
                    delegated_run_id: Some(delegated_run_id.clone()),
                    task_id: parent_name.to_string(),
                    name: parent_name.to_string(),
                    identity: None,
                    status,
                    tool_count: 0,
                    tokens: 0,
                    current_action,
                    completion_summary: Some(
                        authoritative
                            .human_review
                            .unwrap_or_else(|| investigation_summary.clone()),
                    ),
                    lines_added: stats.lines_added,
                    lines_removed: stats.lines_removed,
                    completed_plan_task: None,
                    conversation_event: None,
                });
            }
        }

        let warnings = if durable_run_started {
            Vec::new()
        } else {
            vec![
                "This synchronous delegated build ran without a durable delegated-run record."
                    .to_string(),
            ]
        };
        ToolResult::success_data_with(payload, warnings, None, None)
    }
}

fn group_terminal_state(stage: DelegatedRunStage) -> crate::storage::DelegationGroupState {
    match stage {
        DelegatedRunStage::Complete => crate::storage::DelegationGroupState::Complete,
        DelegatedRunStage::Degraded => crate::storage::DelegationGroupState::Degraded,
        DelegatedRunStage::Failed => crate::storage::DelegationGroupState::Failed,
        DelegatedRunStage::Cancelled => crate::storage::DelegationGroupState::Cancelled,
        DelegatedRunStage::Created
        | DelegatedRunStage::Running
        | DelegatedRunStage::Synthesizing => crate::storage::DelegationGroupState::Failed,
    }
}

