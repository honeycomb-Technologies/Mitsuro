    async fn wait_until_terminal(registry: &ProcessRegistry, owner_id: &str, process_id: &str) {
        tokio::time::timeout(Duration::from_secs(2), async {
            loop {
                if registry
                    .get_for_user(owner_id, process_id)
                    .await
                    .is_some_and(|process| !process.is_active())
                {
                    return;
                }
                tokio::time::sleep(Duration::from_millis(10)).await;
            }
        })
        .await
        .expect("tracked process should reach a terminal state");
    }

